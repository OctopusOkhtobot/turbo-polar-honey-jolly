function judgeText(text, correct) {
	const folded = arabicFold(text);
	if (!folded) return "wrong";
	if (correct === "mutlaq") return folded.includes("مطلق") ? "right" : "wrong";
	if (correct === "izhar") {
		if (folded.includes("مطلق") || folded.includes("ادغام") || folded.includes("اخفاء") || folded.includes("اقلاب")) return "wrong";
	}
	if ((correct === "idgham-gh" || correct === "idgham-nogh") && folded.includes("ادغام") && !folded.includes("غن")) return "partial";
	return (LABELS[correct] ?? []).some((key) => folded.includes(arabicFold(key))) ? "right" : "wrong";
}
